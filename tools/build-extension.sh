#!/usr/bin/env bash
# Packs `extension/` into the archive the app ships and the release publishes.
#
#   tools/build-extension.sh             # vendor/extension/Downloader-extension.zip
#   tools/build-extension.sh dist        # and a copy in dist/
#   tools/build-extension.sh --reset     # restore the committed asset stub
#
# The archive holds a top-level `Downloader-extension/` folder, which is what
# Chrome's "Load unpacked" wants once it is extracted. `lib/extension-asset.ts`
# lists the archive for `nsh package`, and `tools/package.sh` restores that
# stub afterwards, so the import never points at a gitignored build artifact.
set -euo pipefail
cd "$(dirname "$0")/.."

ASSET=lib/extension-asset.ts
STUB='// Generated by tools/build-extension.sh: do not edit.
// The committed stub ships no archive, so a fresh clone builds and tests.
export const extensionArchive: string | null = null;'

if [ "${1:-}" = "--reset" ]; then
  printf '%s\n' "$STUB" > "$ASSET"
  exit 0
fi

# Same requirement as tools/prepare-aria2.sh: Windows runners expose `python`.
PYTHON=$(command -v python3 || command -v python || true)
if [ -z "$PYTHON" ]; then
  echo "python3 is required to build the browser extension archive" >&2
  exit 1
fi

OUT=${1:-}
if [ -n "$OUT" ]; then
  mkdir -p "$OUT"
  OUT=$(cd "$OUT" && pwd)
fi

"$PYTHON" - "$OUT" <<'PY'
import json
import os
import re
import shutil
import sys
import zipfile

out_dir = sys.argv[1] if len(sys.argv) > 1 else ""
root = os.getcwd()
source = os.path.join(root, "extension")
staging = os.path.join(root, "vendor", "extension")
name = "Downloader-extension.zip"
target = os.path.join(staging, name)

def read_json(path):
    # Windows' Python defaults to a legacy code page; both files are UTF-8.
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


app_version = read_json(os.path.join(root, "nsh.json"))["version"]
# Chrome takes 1-4 dot-separated integers; a build suffix ("1.0.1+gabc") is not one.
match = re.match(r"\d+(?:\.\d+){0,3}", app_version)
manifest = read_json(os.path.join(source, "manifest.json"))
if match:
    manifest["version"] = match.group(0)
manifest_bytes = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")

files = []
for base, dirs, names in os.walk(source):
    dirs.sort()
    for entry in sorted(names):
        if entry.startswith("."):
            continue
        # Zip entries always use forward slashes, also when this runs on Windows.
        files.append(os.path.relpath(os.path.join(base, entry), source).replace(os.sep, "/"))
files.sort()

os.makedirs(staging, exist_ok=True)
# A fixed timestamp keeps the archive byte-identical between builds.
stamp = (2020, 1, 1, 0, 0, 0)
with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
    for relative in files:
        data = manifest_bytes if relative == "manifest.json" else open(os.path.join(source, relative), "rb").read()
        info = zipfile.ZipInfo(f"Downloader-extension/{relative}", date_time=stamp)
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        archive.writestr(info, data)

if out_dir:
    copy = os.path.join(out_dir, name)
    shutil.copyfile(target, copy)

size = os.path.getsize(target)
print(f"built {name} ({size // 1024} KiB, {len(files)} files, extension {manifest['version']})")
PY

cat > "$ASSET" <<'TS'
// Generated by tools/build-extension.sh: do not edit.
import archive from "../vendor/extension/Downloader-extension.zip?url";

export const extensionArchive: string | null = archive;
TS
